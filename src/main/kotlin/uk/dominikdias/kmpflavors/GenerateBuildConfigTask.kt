package uk.dominikdias.kmpflavors

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/** Writes the BuildConfig object for the active variant. Writes nothing when no package name is set. */
@CacheableTask
abstract class GenerateBuildConfigTask : DefaultTask() {
    @get:Input
    @get:Optional
    abstract val packageName: Property<String>

    @get:Input
    abstract val className: Property<String>

    @get:Input
    abstract val internalVisibility: Property<Boolean>

    /** Rendered declarations, one per field. */
    @get:Input
    abstract val declarations: ListProperty<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        root.mkdirs()
        val pkg = packageName.orNull ?: return
        val dir = root.resolve(pkg.replace('.', '/')).apply { mkdirs() }
        val visibility = if (internalVisibility.get()) "internal" else "public"
        dir.resolve("${className.get()}.kt").writeText(
            buildString {
                appendLine("// Generated by kmp-flavors. Do not edit.")
                appendLine("package $pkg")
                appendLine()
                appendLine("$visibility object ${className.get()} {")
                declarations.get().forEach { appendLine("    $it") }
                appendLine("}")
            },
        )
    }
}
